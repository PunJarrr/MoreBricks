plugins {
    id("net.neoforged.moddev") version "2.0.148"
    id("neoforge-mutex")
    // Uploads to Modrinth and CurseForge (https://modmuss50.github.io/mod-publish-plugin/)
    id("me.modmuss50.mod-publish-plugin") version "2.2.1"
}

val modId = sc.properties["mod.id"]
val modVersion = sc.properties["mod.version"]

version = "$modVersion+${sc.current.version}"
base.archivesName = "$modId-neoforge"

val requiredJava: JavaVersion = when {
    sc.current.parsed >= "26.1" -> JavaVersion.VERSION_25
    sc.current.parsed >= "1.20.5" -> JavaVersion.VERSION_21
    else -> JavaVersion.VERSION_17
}

// Resources are generated by the Fabric build of the same Minecraft version (`runDatagen`)
sourceSets.main {
    resources.srcDir(rootProject.file("src/generated/${sc.current.version}"))
}

neoForge {
    version = sc.properties["deps.neo_loader"]

    mods {
        register(modId) {
            sourceSet(sourceSets.main.get())
        }
    }

    runs {
        register("client") {
            gameDirectory = rootProject.file("run/${sc.current.version}-neoforge")
            client()
        }
        register("server") {
            gameDirectory = rootProject.file("run/${sc.current.version}-neoforge")
            server()
        }
    }
}

java {
    withSourcesJar()
    targetCompatibility = requiredJava
    sourceCompatibility = requiredJava

    toolchain {
        vendor = JvmVendorSpec.ADOPTIUM
        languageVersion = JavaLanguageVersion.of(requiredJava.majorVersion)
    }
}

tasks {
    processResources {
        val props = mapOf(
            "id" to modId,
            "name" to sc.properties["mod.name"],
            "version" to modVersion,
            "minecraft" to sc.properties["mod.mc_compat"],
            // Newer NeoForge deprecates `logoFile` in favour of `iconFile`
            "icon_key" to if (sc.current.parsed >= "26.1") "iconFile" else "logoFile",
        )
        inputs.properties(props)
        // NeoForge before 1.20.5 reads META-INF/mods.toml
        val legacyModsToml = sc.current.parsed < "1.20.5"
        filesMatching("META-INF/neoforge.mods.toml") {
            expand(props)
            if (legacyModsToml) path = "META-INF/mods.toml"
        }

        exclude("fabric.mod.json", ".cache")
    }

    named("createMinecraftArtifacts") {
        dependsOn("stonecutterGenerate")
    }

    withType<Jar> {
        val id = modId
        inputs.property("mod_id", id)
        from(rootProject.file("LICENSE")) { rename { "${it}_$id" } }
        // Required by the Vanilla Tweaks terms (https://vanillatweaks.net/terms/)
        from(rootProject.file("credits.txt"))
    }

    register<Copy>("buildAndCollect") {
        group = "build"
        description = "Builds the mod jar and copies it to `build/libs/{mod version}/`"

        inputs.property("version", modVersion)
        from(jar.flatMap { it.archiveFile })
        into(rootProject.layout.buildDirectory.dir("libs/$modVersion"))
    }
}

publishMods {
    val releases = sc.properties.rawOrNull("mod", "mc_releases")?.asList().orEmpty().map { it.toString() }
    val modrinthToken = providers.environmentVariable("MODRINTH_TOKEN")
    val curseforgeToken = providers.environmentVariable("CURSEFORGE_TOKEN")

    file = tasks.jar.flatMap { it.archiveFile }
    displayName = "${sc.properties["mod.name"]} $modVersion (NeoForge ${sc.current.version})"
    version = "$modVersion+${sc.current.version}-neoforge"
    changelog = providers.environmentVariable("CHANGELOG").orElse("See https://github.com/PunJarrr/MoreBricks/releases")
    type = STABLE
    modLoaders.add("neoforge")
    // Without tokens, `publishMods` only checks the configuration
    dryRun = modrinthToken.map { false }.orElse(true)

    modrinth {
        projectId = sc.properties["publish.modrinth"]
        accessToken = modrinthToken
        minecraftVersions.addAll(releases)
    }
    curseforge {
        projectId = sc.properties["publish.curseforge"]
        accessToken = curseforgeToken
        minecraftVersions.addAll(releases)
        javaVersions.add(requiredJava)
        clientRequired = true
        serverRequired = true
    }
}
